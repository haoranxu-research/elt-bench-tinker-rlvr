GROUPS = ("postgres", "mongodb", "aws_s3", "flat_files", "custom_api")


class _TerraformReference(str):
    """An expression generated by the host rather than a literal input value."""


def _escape_templates(value):
    if isinstance(value, _TerraformReference):
        return str(value)
    if isinstance(value, str):
        return value.replace("${", "$${").replace("%{", "%%{")
    if isinstance(value, dict):
        return {key: _escape_templates(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_escape_templates(item) for item in value]
    return value


def streams(config: dict) -> dict[str, dict[str, str]]:
    result = {
        name: {table: config[name]["config"]["sync_mode"] for table in config[name]["config"]["tables"]}
        for name in ("postgres", "mongodb", "custom_api")
    }
    for name, entries in (("aws_s3", config["aws_s3"]["data"]), ("flat_files", config["flat_files"])):
        result[name] = {entry["table"]: entry["sync_mode"] for entry in entries}
    return result


def select_streams(text: str, available: Mapping[str, Mapping[str, str]]) -> dict[str, list[str]]:
    try:
        payload = json.loads(text)
    except (ValueError, RecursionError):
        raise PipelineError(
            "load.json must contain valid JSON. Use write_pipeline_file to replace it with a sources object "
            "using the groups and streams from read_task."
        ) from None
    group = next(iter(available))
    stream = next(iter(available[group]))
    example = json.dumps({"sources": {group: [stream]}})
    if not isinstance(payload, dict) or set(payload) != {"sources"}:
        raise PipelineError(f"load.json requires exactly one top-level key, sources. Example shape: {example}. "
                            "Use write_pipeline_file to include every group and stream listed by read_task.")
    selected = payload["sources"]
    if not isinstance(selected, dict) or not selected.keys() <= available.keys():
        raise PipelineError("sources must be an object using approved groups: " + ", ".join(available))
    for group, names in selected.items():
        if (not isinstance(names, list) or
            any(not isinstance(name, str) or name not in available[group] for name in names) or
            len(set(names)) != len(names)):
            raise PipelineError(f"source groups require unique approved stream names. For {group}, use a nonempty "
                                f"array containing names from: {', '.join(available[group])}.")
    missing = [f"{group}.{name}" for group, names in available.items()
               for name in names if name not in selected.get(group, ())]
    if missing:
        raise PipelineError(f"Missing required streams: {', '.join(missing)}. Keep every listed stream. "
                            "For a connection failure, restore connectivity and retry the complete saved manifest.")
    return selected


def terraform_plan(config: dict, selected: dict[str, list[str]], database: str,
                   credential: dict | None, server_url: str) -> dict:
    airbyte = config["Airbyte"]["config"]
    ids = streams(config)
    resources: dict[str, dict] = {}
    outputs = {}
    destination = "airbyte_destination_snowflake" if credential is not None else "airbyte_destination_postgres"

    def add(resource_type: str, key: str, payload: dict) -> None:
        resources.setdefault(resource_type, {})[key] = payload

    def ref(resource_type: str, key: str, field: str) -> str:
        return _TerraformReference("${" + f"{resource_type}.{key}.{field}" + "}")

    def source(resource_type: str, key: str, definition: str, options: dict | str,
               group: str, names: list[str]) -> None:
        add(resource_type, key, {
            "name": f"{database}-{key}", "workspace_id": airbyte["workspace_id"],
            "definition_id": airbyte[definition], "configuration": options,
        })
        add("airbyte_connection", key, {
            "name": f"{database}-{key}", "status": "active",
            "schedule": {"schedule_type": "manual"},
            "source_id": ref(resource_type, key, "source_id"),
            "destination_id": ref(destination, "books", "destination_id"),
            "namespace_definition": airbyte["namespace_definition"],
            "configurations": {"streams": [{"name": name, "sync_mode": ids[group][name]} for name in names]},
        })
        outputs[key] = ref("airbyte_connection", key, "connection_id")

    if credential is None:
        pg = config["postgres"]["config"]
        destination_auth = {
            "host": pg["host"], "port": pg["port"], "database": database, "schema": "books_probe",
            "username": pg["user"], "password": pg["password"],
            "ssl_mode": {"disable": {}}, "tunnel_method": {"no_tunnel": {}},
        }
    elif "private_key_file" in credential:
        key = {"private_key": Path(credential["private_key_file"]).read_text(encoding="ascii")}
        if credential.get("private_key_file_pwd"):
            key["private_key_password"] = credential["private_key_file_pwd"]
        destination_auth = {"key_pair_authentication": key}
    else:
        destination_auth = {"username_and_password": {"password": credential["password"]}}
    add(destination, "books", {
        "name": f"{database}-books", "workspace_id": airbyte["workspace_id"],
        "definition_id": (airbyte["snowflake_definition_id"] if credential is not None
                          else "25c5221d-dce2-4163-ade9-739ef790f503"),
        "configuration": destination_auth if credential is None else {
            "host": credential["host"], "database": database, "schema": "BOOKS",
            "warehouse": credential["warehouse"], "role": credential["role"],
            "username": credential["user"],
            "credentials": destination_auth,
        },
    })
    if names := selected.get("postgres"):
        pg = config["postgres"]["config"]
        source("airbyte_source_postgres", "postgres", "postgres_definition_id", {
            "database": pg["database"], "host": pg["host"], "port": pg["port"],
            "username": pg["user"], "password": pg["password"], "schemas": [pg["schema"]],
            "ssl_mode": {"disable": {}}, "tunnel_method": {"no_tunnel": {}},
            "replication_method": {"scan_changes_with_user_defined_cursor": {}},
        }, "postgres", names)
    if names := selected.get("mongodb"):
        mongo = config["mongodb"]["config"]
        source("airbyte_source_mongodb_v2", "mongodb", "mongodb_definition_id", {
            "database_config": {"self_managed_replica_set": {
                "connection_string": mongo["connection_string"], "database": mongo["database"],
                "schema_enforced": True,
            }},
        }, "mongodb", names)
    if names := selected.get("aws_s3"):
        s3 = config["aws_s3"]
        paths = {item["table"]: urlsplit(item["path"]) for item in s3["data"]}
        buckets = {paths[name].netloc for name in names}
        if len(buckets) != 1:
            raise ValueError("books S3 streams must share a bucket")
        source("airbyte_source_s3", "s3", "s3_definition_id", {
            "bucket": buckets.pop(), "endpoint": s3["AWS_ENDPOINT_URL"],
            "region_name": s3["AWS_DEFAULT_REGION"], "aws_access_key_id": s3["AWS_ACCESS_KEY_ID"],
            "aws_secret_access_key": s3["AWS_SECRET_ACCESS_KEY"],
            "streams": [{"name": name, "globs": [paths[name].path.lstrip("/")],
                         "format": {"csv_format": {}}} for name in names],
        }, "aws_s3", names)
    for item in config["flat_files"]:
        name = item["table"]
        if name in selected.get("flat_files", []):
            source("airbyte_source_file", name, "files_definition_id", {
                "dataset_name": name, "format": item["format"], "url": item["path"],
                "provider": {"https_public_web": {}},
            }, "flat_files", [name])
    if names := selected.get("custom_api"):
        options = config["custom_api"]["config"]["configuration"]
        source("airbyte_source_custom", "custom_api", "custom_api_definition_id",
               json.dumps(options), "custom_api", names)
    return _escape_templates({
        "provider": {"airbyte": {"server_url": server_url, "username": airbyte["username"],
                                  "password": airbyte["password"]}},
        "resource": resources,
        "output": {"connections": {"value": outputs}},
    })


def private_environment() -> dict[str, str]:
    """Preserve executable lookup and OS requirements, excluding product credentials."""
    keys = {"PATH", "SYSTEMROOT", "WINDIR", "COMSPEC", "PATHEXT", "TEMP", "TMP",
            "HOME", "USERPROFILE", "APPDATA", "LOCALAPPDATA", "LANG", "LC_ALL",
            "SSL_CERT_FILE", "SSL_CERT_DIR", "TF_CLI_CONFIG_FILE"}
    return {key: value for key, value in os.environ.items() if key.upper() in keys}


class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


class _ConnectionSetupError(PipelineError):
    """A failed connection setup that may be safe to retry."""

    def __init__(self, message: str, unconfirmed_connections: tuple[str, ...] = ()):
        super().__init__(message)
        self.unconfirmed_connections = unconfirmed_connections


class _TransientAirbyteError(PipelineError):
    """A request encountered a temporary gateway or transport failure."""


class AirbyteRun:
    """Manage only the connections belonging to this private Terraform state."""

    def __init__(self, directory: Path, terraform: str, url: str, timeout: int):
        self.directory = directory
        self.terraform = terraform
        self.url = url.rstrip("/")
        self.timeout = timeout
        self.grading_deadline: float | None = None
        self.action_deadline: float | None = None
        self.apply_started = False
        self.active_job: str | None = None
        self.jobs: list[dict[str, str]] = []
        self._opener = build_opener(ProxyHandler({}), NoRedirect())

    def _time_left(self, limit: float) -> float:
        if self.action_deadline is not None:
            remaining = self.action_deadline - time.monotonic()
            if remaining <= 0:
                raise PipelineError("agent action deadline expired during Airbyte load")
            limit = min(limit, remaining)
        return grading_time_left(self.grading_deadline, limit)

    def _tf(self, command: str, *args: str) -> bytes:
        try:
            result = subprocess.run(
                [self.terraform, command, *args], cwd=self.directory, env=private_environment(),
                stdout=subprocess.PIPE if command == "output" else subprocess.DEVNULL,
                stderr=subprocess.PIPE if command == "apply" else subprocess.DEVNULL,
                timeout=self._time_left(self.timeout), check=True,
            )
        except subprocess.TimeoutExpired:
            raise PipelineError(f"Airbyte Terraform {command} timed out") from None
        except subprocess.CalledProcessError as error:
            diagnostic = (error.stderr or b"").decode("utf-8", errors="replace")
            addresses = sorted(set(re.findall(r"\bwith (airbyte_(?:connection|source_[a-z0-9_]+)\.[a-z][a-z0-9_]*),",
                                              diagnostic)))
            scope = f" for {', '.join(addresses)}" if addresses else ""
            failure = f"Airbyte Terraform {command} failed (exit {error.returncode}){scope}"
            # Retry an explicit catalog-discovery failure, where the connection
            # creation did not reach the mutation. Keep raw provider errors private.
            discovery = re.search(r"fail\w* to (?:discover|fetch)(?: [\w-]+){0,4} (?:schema|catalog)|"
                                  r"(?:discovery|schema catalog) (?:has )?failed|"
                                  r"(?:could not|unable to) (?:discover|fetch) (?:the )?(?:schema|catalog)",
                                  diagnostic, re.I)
            permanent = re.search(r"unauthori[sz]ed|forbidden|invalid credentials|certificate verify failed|"
                                  r"authentication failed|\b(?:401|403|404)\b", diagnostic, re.I)
            opaque = "an unexpected problem has occurred" in diagnostic.lower()
            if (command == "apply" and addresses and (discovery or opaque) and not permanent
                    and all(address.startswith("airbyte_connection.") for address in addresses)):
                reason = "source catalog discovery failed" if discovery else "Airbyte reported a connection setup error"
                raise _ConnectionSetupError(
                    f"{failure}: {reason}. Check the affected connector's network and TLS logs. "
                    "Restore access to the original source and retry the saved complete manifest.",
                    tuple(address.split(".", 1)[1] for address in addresses) if opaque else (),
                ) from None
            raise PipelineError(f"{failure}; check the private Airbyte workload logs") from None
        except OSError:
            raise PipelineError(f"could not launch Terraform {command}") from None
        return result.stdout

    def provision(self, main_tf: Path, plan: dict, username: str, password: str) -> None:
        self.directory.mkdir()
        (self.directory / "versions.tf").write_bytes(main_tf.read_bytes())
        (self.directory / "pipeline.tf.json").write_text(json.dumps(plan), encoding="utf-8")
        self.auth = base64.b64encode(f"{username}:{password}".encode()).decode()
        self._tf("init", "-input=false", "-no-color")
        self.apply_started = True
        options = ("-auto-approve", "-input=false", "-no-color", "-parallelism=1")
        try:
            self._tf("apply", *options)
        except _ConnectionSetupError as error:
            if error.unconfirmed_connections and not self._connections_absent(plan, error.unconfirmed_connections):
                raise PipelineError(f"{error} No retry: the connection inventory could not rule out a prior creation.") from None
            # Reuse the same state and plan. No sync has been queued yet.
            time.sleep(min(2, self._time_left(2)))
            self._tf("apply", *options)
        try:
            connections = json.loads(self._tf("output", "-json", "connections"))
        except ValueError:
            raise PipelineError("Airbyte returned invalid connection metadata") from None
        if (not isinstance(connections, dict) or
            set(connections) != set(plan["output"]["connections"]["value"]) or
            any(not isinstance(item, str) or not item for item in connections.values())):
            raise PipelineError("Airbyte did not return all connection identifiers")
        for name, identifier in sorted(connections.items()):
            self._sync(name, identifier)

    def _connections_absent(self, plan: dict, keys: tuple[str, ...]) -> bool:
        try:
            resources = plan["resource"]
            scope = next(kind["books"]["workspace_id"] for name, kind in resources.items()
                         if name.startswith("airbyte_destination_"))
            names = {resources["airbyte_connection"][key]["name"] for key in keys}
            client = AirbyteRun(self.directory, self.terraform, self.url.removesuffix("/api/public/v1") + "/api/v1",
                                self.timeout)
            client.auth = self.auth
            client.action_deadline, client.grading_deadline = self.action_deadline, self.grading_deadline
            rows = client._request("POST", "/connections/list", {"workspaceId": scope})["connections"]
            return isinstance(rows, list) and all(isinstance(row.get("name"), str) and row["name"] not in names
                                                  for row in rows)
        except GradingTimeout:
            raise
        except (PipelineError, KeyError, AttributeError, TypeError, StopIteration):
            return False

    def _request(self, method: str, path: str, body: dict | None = None) -> dict:
        try:
            return self._request_once(method, path, body)
        except _TransientAirbyteError:
            if method != "GET":
                raise
            time.sleep(min(2, self._time_left(2)))
            return self._request_once(method, path, body)

    def _request_once(self, method: str, path: str, body: dict | None) -> dict:
        headers = {"Authorization": f"Basic {self.auth}", "Accept": "application/json",
                   "Content-Type": "application/json"}
        request = Request(self.url + path, method=method, headers=headers,
                          data=json.dumps(body).encode() if body else None)
        try:
            with self._opener.open(request, timeout=self._time_left(15)) as response:
                data = response.read(1_048_577)
        except HTTPError as error:
            kind = _TransientAirbyteError if error.code in {408, 429, 502, 503, 504} else PipelineError
            raise kind(f"Airbyte jobs API returned HTTP {error.code}; check the local Airbyte gateway") from None
        except (URLError, OSError):
            raise _TransientAirbyteError("Airbyte jobs API connection failed; check the local Airbyte tunnel") from None
        try:
            result = json.loads(data) if data else {}
        except ValueError:
            raise PipelineError("Airbyte returned an invalid job response") from None
        if len(data) > 1_048_576 or not isinstance(result, dict):
            raise PipelineError("Airbyte returned an invalid job response")
        return result

    def _sync(self, name: str, identifier: str) -> None:
        started = datetime.now(timezone.utc).isoformat()
        job = self._request("POST", "/jobs", {"jobType": "sync", "connectionId": identifier})
        job_id = str(job.get("jobId", ""))
        if not job_id.isascii() or not job_id.isdecimal():
            raise PipelineError("Airbyte did not return a valid sync job ID")
        self.active_job = job_id
        deadline = time.monotonic() + self._time_left(self.timeout)
        while time.monotonic() < deadline:
            status = self._request("GET", f"/jobs/{job_id}").get("status")
            if status in {"succeeded", "failed", "cancelled", "canceled", "incomplete"}:
                self.active_job = None
                self.jobs.append({"stream_group": name, "job_id": job_id, "status": status,
                                  "started_utc": started, "finished_utc": datetime.now(timezone.utc).isoformat()})
                if status == "succeeded":
                    return
                raise PipelineError(f"Airbyte sync {name} ended with status {status}")
            time.sleep(min(3, max(0, deadline - time.monotonic())))
        self.jobs.append({"stream_group": name, "job_id": job_id, "status": "timeout",
                          "started_utc": started, "finished_utc": datetime.now(timezone.utc).isoformat()})
        raise PipelineError(f"Airbyte sync {name} timed out")

    def cleanup(self) -> None:
        self.grading_deadline = None
        self.action_deadline = None
        try:
            if self.active_job:
                self._request("DELETE", f"/jobs/{self.active_job}")
                self.active_job = None
        finally:
            if self.apply_started:
                self._tf("destroy", "-auto-approve", "-input=false", "-no-color", "-parallelism=1")
                self.apply_started = False
